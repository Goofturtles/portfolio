let uid = 0
const reduced = () => document.documentElement.classList.contains('calm') || matchMedia('(prefers-reduced-motion: reduce)').matches

export function createArjun() {
  const P = `ga${(++uid).toString(36)}${Math.random().toString(36).slice(2, 6)}-` // unique even if this module loads twice
  const el = document.createElement('div')
  el.className = 'ga'
  el.setAttribute('aria-hidden', 'true')
  el.dataset.pose = 'idle'
  el.innerHTML = svg(P)
  const $ = (s) => el.querySelector(s)
  const mp = $('.ga-mp')
  const iris = $('.ga-iris')
  const drift = [$('.ga-dr'), $('.ga-swN'), $('.ga-swF')]
  // everything a pose keyframes, plus the <svg> (idle breathing), cross-fades on a pose change
  const groups = [el.firstElementChild, ...el.querySelectorAll('.ga-an')]
  let cur = 'idle', poseAt = 0, dir = 1, lx = 0, ly = 0, lastM = 0, dead = false, blends = [], tBlink = 0, tOpen = 0, nBlink = 0

  // switch pose state, cross-fading every keyframed group from where it is now into the new pose as it plays
  // (a single offset-0 keyframe: the end is the live underlying value, so the new animations start at once)
  function blend(change) {
    const still = reduced()
    const from = still ? null : groups.map((g) => getComputedStyle(g).transform)
    for (const a of blends) a.cancel()
    blends = []
    change()
    if (still) return
    groups.forEach((g, i) => {
      if (getComputedStyle(g).transform !== from[i]) blends.push(g.animate([{ transform: from[i], offset: 0 }], { duration: BLEND_MS, easing: 'cubic-bezier(.3,0,.2,1)' }))
    })
  }

  function pose(name) {
    if (dead || !POSES.includes(name)) return
    if (name === cur) {
      if (name !== 'wave' && name !== 'cheer') return
      blend(() => { for (const a of el.getAnimations({ subtree: true })) if (a.animationName && a.animationName.startsWith('ga-x-')) { a.currentTime = 0; a.play() } })
    } else blend(() => { el.dataset.pose = cur = name })
    if (cur !== 'idle') settle()
    poseAt = performance.now()
  }

  function face(d) {
    dir = d < 0 ? -1 : 1
    el.classList.toggle('ga-l', dir < 0)
    look(lx, ly)
  }

  function point(deg) {
    deg = Math.max(-45, Math.min(100, +deg || 0))
    const up = deg <= 20 ? deg : 20 + (deg - 20) * 0.25 // the elbow stays out to the side so the hand clears the big head
    el.style.setProperty('--ga-s', `${(-90 - up).toFixed(1)}deg`)
    el.style.setProperty('--ga-e', `${(up - deg).toFixed(1)}deg`)
    el.style.setProperty('--ga-t', `${(-Math.max(0, deg) / 28).toFixed(2)}deg`)
  }

  function mouth(v) {
    const i = v > 0 ? (v < 1 ? Math.round(v * 100) : 100) : 0
    if (i !== lastM) mp.setAttribute('d', MOUTH[(lastM = i)])
  }

  function look(x, y) {
    lx = Math.max(-1, Math.min(1, +x || 0)); ly = Math.max(-1, Math.min(1, +y || 0))
    iris.style.transform = `translate(${(lx * dir * 1.8).toFixed(2)}px,${(ly * 1.4).toFixed(2)}px)` // screen x, so mirrored
  }

  // idle life without a per-frame cost: every third blink the head tilts and the arms shift a little (1.5 s transitions)
  function fidget() {
    const idle = cur === 'idle', hold = cur === 'point' || cur === 'wave'
    if (!(idle || hold) || reduced()) return
    drift[0].style.transform = `rotate(${(Math.random() * 2.2 - 1.3).toFixed(2)}deg)`
    drift[1].style.transform = `rotate(${(Math.random() * 2.4).toFixed(2)}deg)`
    drift[2].style.transform = idle ? `rotate(${(-Math.random() * 2.4).toFixed(2)}deg)` : ''
  }
  function settle() { for (const d of drift) d.style.transform = '' }

  function blink() {
    if (dead) return
    if (!(cur === 'cheer' && (reduced() || performance.now() - poseAt < 1500))) {
      el.classList.add('ga-bk')
      tOpen = setTimeout(() => el.classList.remove('ga-bk'), 140)
    }
    if (++nBlink % 3 === 0) fidget()
    tBlink = setTimeout(blink, 2000 + Math.random() * 4000)
  }
  tBlink = setTimeout(blink, 1200 + Math.random() * 2500)
  point(30)

  function destroy() {
    dead = true
    clearTimeout(tBlink); clearTimeout(tOpen)
    for (const a of blends) a.cancel()
    el.remove()
  }

  // read once per walk (a style + layout read), not per frame
  const stepSeconds = () => {
    const raw = getComputedStyle(el).getPropertyValue('--ga-step').trim(), n = parseFloat(raw)
    return n > 0 ? (raw.endsWith('ms') ? n / 1000 : n) : STEP_MS / 1000
  }
  const heightPx = () => parseFloat(getComputedStyle(el).height) || 150

  return {
    el, pose, face, point, mouth, look, destroy,
    stride: STRIDE, // el heights per step
    get stepMs() { return stepSeconds() * 1000 },
    get walkSpeed() { return (STRIDE * heightPx()) / stepSeconds() }, // px/s for the current height and --ga-step
  }
}

// Lip-sync driver: reads a Web Audio AnalyserNode once per frame while speech plays and calls guide.mouth().
//   const ctx = new AudioContext(), an = ctx.createAnalyser(); an.fftSize = 1024
//   ctx.createMediaElementSource(ttsAudio).connect(an).connect(ctx.destination)   // or a BufferSource / TTS stream
//   const stop = lipSync(guide, an)   // ... stop() when the line ends (closes the mouth)
// Level = RMS of the newest ~20 ms of samples (time domain, so the analyser adds no smoothing lag), normalised to the
// recent loudest syllable (any TTS volume opens the mouth fully on stressed syllables), gated so breaths and room noise
// keep it shut, then a fast attack / slower release so it snaps open on each syllable and closes between words. The
// value shown is delayed by the device's output latency, so the lips move with what is heard, not with what the
// audio thread has rendered (matters on Bluetooth, where that can be 100-250 ms).
export function lipSync(guide, analyser) {
  const ctx = analyser.context
  const buf = new Float32Array(analyser.fftSize)
  const q = [] // [audio time, level]
  let v = 0, peak = 0.02, raf = 0
  const tick = () => {
    analyser.getFloatTimeDomainData(buf)
    let s = 0
    for (let i = 0; i < buf.length; i++) s += buf[i] * buf[i]
    const rms = Math.sqrt(s / buf.length)
    peak = Math.max(rms, peak * 0.996, 0.02)
    const x = rms / peak
    const target = x < 0.14 ? 0 : Math.min(1, (x - 0.14) / 0.76)
    v += (target - v) * (target > v ? 0.7 : 0.32)
    const now = ctx.currentTime, lag = Math.max(0, (ctx.outputLatency || ctx.baseLatency || 0) - 0.017)
    q.push([now, v < 0.02 ? 0 : v])
    while (q.length > 1 && q[1][0] <= now - lag) q.shift()
    guide.mouth(q[0][1])
    raf = requestAnimationFrame(tick)
  }
  raf = requestAnimationFrame(tick)
  return () => { cancelAnimationFrame(raf); guide.mouth(0) }
}

// Mini Arjun: the cartoon guide (Fluent 3D emoji style). One inline SVG, CSS-driven motion (guide.css).
//
//   import { createArjun, lipSync } from './arjun.js'
//   const g = createArjun()          // { el, pose, face, point, mouth, look, destroy } + walkSpeed, stepMs, stride
//   stage.appendChild(g.el)          // position g.el by its bottom-centre (the feet); size it with --ga-h (150px)
//   g.face(-1); g.pose('walk')       // then move g.el at g.walkSpeed px/s, starting now (see "Walking in sync")
//   g.point(45); g.pose('point')     // raise the facing-side arm 45 degrees above horizontal
//   g.mouth(v)                       // 0 closed smile .. 1 open; one attribute write, call it every frame
//   const stop = lipSync(g, analyser) // or let lipSync() drive mouth() from a Web Audio AnalyserNode
//
// Integration notes
// - Walking in sync: call pose('walk') and start moving el in the same frame at g.walkSpeed px/s (a getter: it reads
//   el's rendered height and --ga-step, so read it once per walk, not per frame). The shoe on the floor then stays
//   put: the walk cycle (guide.css, generated by checks/gen-walk.mjs) carries the flat stance sole back at exactly
//   STRIDE * height px per step, and the body bob is derived from that sole, so it neither sinks nor hovers. A faster
//   or slower walk: set --ga-step on el (a plain time, e.g. .35s) and read walkSpeed again; walkSpeed =
//   STRIDE * height / step seconds. Stop moving when you call pose() with anything else. The cycle starts with the
//   near shoe planted under the hip, as when standing, so the start only settles by the hips drawing in (about 3% of
//   the height, over the 240 ms pose blend). Walk a whole number of steps (n steps = n * stepMs ms and
//   n * STRIDE * height px) and the walk also ends with a shoe under the hip, so the stop is just as clean. Stopped
//   mid-stride, the shoes ease back under the hips during the blend (up to about 8% of the height).
// - Lip-sync: route the TTS audio through an AnalyserNode and hand it to lipSync(guide, analyser); call the returned
//   stop() when the line ends (it closes the mouth). It opens the mouth a frame or two into each syllable and closes
//   it between words, compensating for the device's output latency.
// - Pivots use transform-box: view-box with absolute user-unit origins, not fill-box, on purpose: a limb group's
//   fill-box grows as the joint inside it bends, so a fill-box pivot drifts mid-wave. Please don't "fix" it back.
// - Cost: idle breathing is a composited transform on the <svg> (no SVG relayout per frame); the small head and arm
//   shifts are occasional CSS transitions started from the blink timer. JavaScript only switches data-pose / classes,
//   writes the mouth clip path (mouth), the pupils' transform (look) and three angles (point), and cross-fades pose
//   changes with a 240 ms Web Animations blend into the live new pose. Blinks: a timer, every 2-6 s.

